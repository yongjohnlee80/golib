package facadegen

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func writeCore(t *testing.T, src string) string {
	t.Helper()
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "a.go"), []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	return dir
}

// TestGenerateForwardsEachKindOfName: a type (generic too) as an alias, a func (generic, variadic,
// with several results) as a func calling core's, a const and a var as core's, docs copied; the
// unexported are left out, and the vars test names each var.
func TestGenerateForwardsEachKindOfName(t *testing.T) {
	dir := writeCore(t, `package core

import "strings"

// Box is a box.
type Box struct{ n int }

type Pair[K comparable, V any] struct{ k K; v V }

type hidden int

// Up is a key.
const Up = 1

var (
	// ErrX is an error.
	ErrX = strings.ToUpper("x")
	quiet = 2
)

// Join joins.
func Join(sep string, parts ...string) string { return strings.Join(parts, sep) }

func Keys[K comparable, V any](m map[K]V) ([]K, int) { return nil, len(m) }

func Run(fn func(id string) bool) {}

func hide() {}

func (b *Box) Size() int { return b.n }
`)
	facade, vars, err := Generate(dir)
	if err != nil {
		t.Fatal(err)
	}
	src := string(facade)
	for _, want := range []string{
		"// Code generated by tui/widget/internal/facadegen; DO NOT EDIT.",
		"// Box is a box.\ntype Box = core.Box",
		"type Pair[K comparable, V any] = core.Pair[K, V]",
		"// Up is a key.\n\tUp = core.Up",
		"// ErrX is an error.\n\tErrX = core.ErrX",
		"// Join joins.\nfunc Join(a0 string, a1 ...string) string {\n\treturn core.Join(a0, a1...)\n}",
		"func Keys[K comparable, V any](a0 map[K]V) ([]K, int) {\n\treturn core.Keys[K, V](a0)\n}",
		"func Run(a0 func(id string) bool) {\n\tcore.Run(a0)\n}",
	} {
		if !strings.Contains(src, want) {
			t.Errorf("the facade lacks %q:\n%s", want, src)
		}
	}
	for _, not := range []string{"hidden", "quiet", "hide", "Size"} {
		if strings.Contains(src, not) {
			t.Errorf("the facade forwards %s, which it should not:\n%s", not, src)
		}
	}
	if !strings.Contains(string(vars), `"ErrX": {widget.ErrX, core.ErrX}`) {
		t.Errorf("the vars test lacks ErrX:\n%s", vars)
	}
}

// TestGenerateRefusesAnUnexportedNameInASignature: an exported func naming a type core does not
// export cannot be forwarded from another package, so Generate says so rather than writing a facade
// that does not compile.
func TestGenerateRefusesAnUnexportedNameInASignature(t *testing.T) {
	dir := writeCore(t, "package core\n\ntype secret int\n\nfunc Open() secret { return 0 }\n")
	if _, _, err := Generate(dir); err == nil || !strings.Contains(err.Error(), "secret") {
		t.Fatalf("Generate = %v, want it to refuse secret", err)
	}
}

// TestGenerateReportsAMissingOrBrokenCore: a folder that is not there, or a file that does not
// parse, is an error.
func TestGenerateReportsAMissingOrBrokenCore(t *testing.T) {
	if _, _, err := Generate(filepath.Join(t.TempDir(), "none")); err == nil {
		t.Error("a missing folder generated a facade")
	}
	if _, _, err := Generate(writeCore(t, "package core\n\nfunc (")); err == nil {
		t.Error("a file that does not parse generated a facade")
	}
}
