import "testing"

// TestVimSentenceMotionsAgainstNeovim walks ) ( 2) and 2( from every position of ten texts and
// compares each landing with headless Neovim's on the same text (nvim --clean, 2026-10-13; none
// of the texts has a line of only blanks, the one place golib differs on purpose).
func TestVimSentenceMotionsAgainstNeovim(t *testing.T) {
	for _, e := range sentenceTable {
		c, _ := coreWith(t, e.text)
		c.SetLine(e.ln, e.col)
		vimSeq(c, e.keys)
		if ln, col := c.Line(); ln != e.wantLn || col != e.wantCol {
			t.Errorf("%q from (%d,%d) by %s: (%d,%d), Neovim (%d,%d)", e.text, e.ln, e.col, e.keys, ln, col, e.wantLn, e.wantCol)
		}
	}
}

